let pool;
export function postgresPool() {
  if (!pool) {
    if (!process.env.SUPABASE_DB_URL)
      throw new Error('SUPABASE_DB_URL is required for Supabase storage.');
    let url;
    try {
      url = new URL(process.env.SUPABASE_DB_URL);
    } catch {
      throw new Error('SUPABASE_DB_URL must be a valid PostgreSQL connection string.');
    }
    if (!['postgres:', 'postgresql:'].includes(url.protocol))
      throw new Error('SUPABASE_DB_URL must be a PostgreSQL connection string.');
    // Keep TLS certificate verification enabled even if a copied URL has weaker SSL options.
    for (const option of ['sslmode', 'sslcert', 'sslkey', 'sslrootcert'])
      url.searchParams.delete(option);
    pool = new pg.Pool({
      connectionString: url.toString(),
      ssl: { rejectUnauthorized: true },
      max: 8,
      connectionTimeoutMillis: 15000,
      idleTimeoutMillis: 30000,
    });
  }
  return pool;
}
export function translateSql(sql, schema) {
  if (!/^radar_(?:main|school_\d{6})$/.test(schema))
    throw new Error('Invalid RADAR database namespace.');
  let text = sql
    .replace(
      /INTEGER PRIMARY KEY AUTOINCREMENT/g,
      'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
    )
    .replace(
      /\(datetime\('now'\)\)/g,
      '(to_char(now() AT TIME ZONE \'UTC\', \'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"\'))',
    )
    .replace(
      /datetime\('now','-(\d+) days'\)/g,
      (_, days) =>
        `to_char((now() AT TIME ZONE 'UTC') - interval '${days} days', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`,
    )
    .replace(/julianday\((\w+)\)/g, '(EXTRACT(EPOCH FROM $1::timestamptz) / 86400.0)');
  const ignore = /INSERT OR IGNORE/i.test(text);
  text = text.replace(/INSERT OR IGNORE/i, 'INSERT');
  if (ignore) text = text.trim().replace(/;$/, '') + ' ON CONFLICT DO NOTHING';
  // Skip quoted SQL string literals when qualifying tables and replacing placeholders.
  let position = 0;
  const identifiers = new Set(TABLES);
  text = text.replace(/'(?:''|[^'])*'|\b[A-Za-z_][A-Za-z_0-9]*\b|\?/g, (token) => {
    if (token.startsWith("'")) return token;
    if (token === '?') return `$${++position}`;
    return identifiers.has(token) ? `"${schema}"."${token}"` : token;
  });
  return text;
}
export class PostgresDatabase {
  dialect = 'postgres';
  transactionClient = null;
  constructor(schema, transport) {
    if (!/^radar_(?:main|school_\d{6})$/.test(schema))
      throw new Error('Invalid RADAR database namespace.');
    this.schema = schema;
    this.transport = transport ?? postgresPool();
  }
  get isTransaction() {
    return this.transactionClient !== null;
  }
  async query(text, values = []) {
    return (this.transactionClient ?? this.transport).query(text, values);
  }
  prepare(sql) {
    const pragma = /^PRAGMA table_info\((\w+)\)$/i.exec(sql.trim());
    const execute = async (values, inserting = false) => {
      if (pragma)
        return this.query(
          'SELECT column_name AS name FROM information_schema.columns WHERE table_schema = $1 AND table_name = $2',
          [this.schema, pragma[1]],
        );
      let text = translateSql(sql, this.schema);
      const table = /^\s*INSERT(?: OR IGNORE)? INTO\s+(\w+)/i.exec(sql)?.[1];
      if (inserting && table && !noIdentity.has(table) && !/\bRETURNING\b/i.test(text))
        text = text.trim().replace(/;$/, '') + ' RETURNING id';
      return this.query(text, values);
    };
    return {
      get: async (...values) => (await execute(values)).rows[0],
      all: async (...values) => (await execute(values)).rows,
      run: async (...values) => {
        const result = await execute(values, true);
        return {
          lastInsertRowid: result.rows[0]?.id,
          changes: result.rowCount ?? result.affectedRows ?? 0,
        };
      },
    };
  }
  async exec(sql) {
    if (/^PRAGMA /i.test(sql)) return;
    if (sql === 'BEGIN') {
      if (this.transactionClient) throw new Error('Transaction already active.');
      this.transactionClient = this.transport.connect
        ? await this.transport.connect()
        : this.transport;
      await this.transactionClient.query('BEGIN');
      return;
    }
    if (sql === 'COMMIT' || sql === 'ROLLBACK') {
      const client = this.transactionClient;
      try {
        await client.query(sql);
      } finally {
        this.transactionClient = null;
        client.release?.();
      }
      return;
    }
    const text = translateSql(sql, this.schema);
    // PGlite and pg both support exec for schema batches through this adapter.
    if (this.transport.exec && !this.transactionClient) return this.transport.exec(text);
    return this.query(text);
  }
  async initializeNamespace() {
    await this.query(`CREATE SCHEMA IF NOT EXISTS "${this.schema}"`);
    await this.query(`REVOKE ALL ON SCHEMA "${this.schema}" FROM PUBLIC`);
  }
  async protectTables() {
    for (const table of TABLES) {
      const exists = await this.query(
        'SELECT 1 FROM information_schema.tables WHERE table_schema = $1 AND table_name = $2',
        [this.schema, table],
      );
      if (!exists.rows.length) continue;
      await this.query(`ALTER TABLE "${this.schema}"."${table}" ENABLE ROW LEVEL SECURITY`);
      await this.query(`REVOKE ALL ON "${this.schema}"."${table}" FROM PUBLIC`);
    }
  }
  async close() {
    if (this.transactionClient) await this.exec('ROLLBACK');
  }
}
